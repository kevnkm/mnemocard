function makeDeck(spec) {
  const { id, title, description, icon, color, category, subject, tags, fields, rows } = spec;
  return {
    id,
    title,
    description,
    icon,
    color,
    category,
    subject,
    tags,
    fieldConfigs: fields,
    cards: rows.map((content, idx) => ({
      id: `${id}-card-${idx + 1}`,
      deckId: id,
      content,
      orderIndex: idx,
    })),
  };
}

